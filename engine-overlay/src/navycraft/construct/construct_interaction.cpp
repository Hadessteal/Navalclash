bool unitNormal(const Vec3d &normal) noexcept
{
    if (!std::isfinite(normal.x) || !std::isfinite(normal.y) ||
            !std::isfinite(normal.z))
        return false;
    const double length_squared = normal.x * normal.x + normal.y * normal.y +
        normal.z * normal.z;
    return std::abs(length_squared - 1.0) <= 1e-4;
}

std::optional<ConstructNodeState> copyState(
    const DynamicConstruct &construct, const LocalNodePos &position)
{
    const auto *state = construct.getNodeState(position);
    return state ? std::optional<ConstructNodeState>(*state) : std::nullopt;
}
